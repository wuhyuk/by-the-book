"""승패·법적 효력 판단, 법률 문서 작성 요청 감지 (CLAUDE.md 절대 규칙 4, MVP_SPEC 8.1 VS3).

LLM 없이 규칙(정규식)으로 먼저 본다. 걸리면 LLM을 부르지 않고 ❔ 판단 불가로 끝낸다.
LLM 추출 결과의 judgment_requested는 근거 구절이 입력에 있을 때만 받아 이 결과와 OR로 합친다
(api/analyze.py). 배지는 규칙 코드(rules.badge.decide_badge)가 정한다.

과하게 잡으면 계산을 막으므로 질문·요청 형태만 잡는다. 놓친 질문은 LLM 판정이 보완한다.
"""

import re

_Q = r"(?:나요|까요|ㄹ까|을까|일까|인가|인지|가요|어요\?|에요\?|죠\?|냐|니\?|\?)"

# 키워드와 질문 어미 사이의 구간. 남의 말을 옮기는 표현("~라던데", "~다고 했는데")은 넘지 않는다
# (예: "업체가 합법이라던데 환불 얼마인가요?"는 금액 질문이다).
_SPAN = r"(?:(?!라던|다고|라고|했는데|던데|라는|이라)[^.!?\n]){0,15}?"
# 문서 작성 요청 형태 ("작성해서 보냈는데"처럼 이미 한 일은 잡지 않는다)
_REQUEST = (
    r"(?:써\s*(?:주|줘|달)|작성\S{0,2}?\s*(?:해\s*(?:주|줘|달)|도와|부탁)"
    r"|만들어\s*(?:주|줘|달)|초안|양식|대신\s*(?:써|작성))"
)

_PATTERNS: tuple[re.Pattern[str], ...] = (
    # 승패 예측
    re.compile(r"이길\s*수|이길까|이기나요|이겨요\?|이길\s*가능성|승소|패소|승산"),
    re.compile(
        r"(?:소송|재판(?!매)|고소|민사|소액\s*심판|지급\s*명령)\S*\s*"
        r"(?:하면|걸면|가면|해서)[^.!?\n]{0,20}?" + _Q
    ),
    # 법적 효력·위법 판단
    re.compile(r"(?:무효|효력|불법|위법|합법|적법|법\s*위반)" + _SPAN + _Q),
    re.compile(r"법적(?:으로|인)?\s*(?:문제|책임|효력|대응|조치|분쟁)" + _SPAN + _Q),
    # 법률 문서 작성
    re.compile(
        r"(?:내용\s*증명|소장(?!님)|고소장|답변서|지급\s*명령\s*신청서|진정서)"
        r"\S{0,6}\s*" + _REQUEST
    ),
)


def detect_judgment_request(text: str) -> bool:
    """승패·법적 효력 판단 또는 법률 문서 작성 요청으로 보이면 True."""
    return any(p.search(text) for p in _PATTERNS)
