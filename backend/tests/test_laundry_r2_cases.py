def test_case_list_matches_approval() -> None:
    approved = [f"R2-{n}" for n in [*range(1, 14), *range(16, 32), *range(33, 44), 45]]
    assert list(CASES) == approved
    assert not set(EXCLUDED) & set(CASES)


@pytest.mark.parametrize("cid", list(CASES))
def test_r2_case(rule: LaundryRule, cid: str) -> None:
    case = CASES[cid]
    e = case["expected"]
    inp = LaundryInput.model_validate_json(_json(case["input"]))
    r = calculate_damage(inp, rule, ON)
    assert r.badge == Badge(e["badge"])
    assert [f.value for f in r.flags] == e["flags"]
    assert r.missing == e["missing"]
    assert [n.value for n in r.notices] == e["notices"]
    assert r.citations == e["citations"]
    assert r.amount == e["amount"]
    if "min" in e:
        assert (r.sensitivity_min, r.sensitivity_max) == (e["min"], e["max"])
        assert r.sensitivity_causes == e["causes"]
        assert r.sensitivity_ratio_alt == e["ratio_alt"]
    display = build_laundry_display(r, rule, inp)
    screen = display.screen_line.text if display.screen_line else None
    assert screen == e["screen"]


