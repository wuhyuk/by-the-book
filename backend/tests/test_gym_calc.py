def test_compare_offer_positions() -> None:
    """MVP_SPEC 5.4 제시액 위치 표."""
    n1, n2 = _results("N1"), _results("N2")
    # N1: B 636,164 ≤ 700,000 < A 784,110 → 안내
    assert compare_offer(700_000, n1).robust is False
    assert compare_offer(700_000, n1).notice == N.OFFER_BETWEEN_A_AND_B
    # N2: 200,000 < B 240,000 → 강건한 ⚠️
    assert compare_offer(200_000, n2).robust is True
    assert compare_offer(200_000, n2).notice is None
    # 경계: 제시액 = B 최솟값 → 안내, 제시액 = A 최댓값 → 없음
    assert compare_offer(636_164, n1).notice == N.OFFER_BETWEEN_A_AND_B
    assert compare_offer(636_164, n1).robust is False
    assert compare_offer(784_110, n1).notice is None
    # 제시액 없음, B 없음 → 판정 없음
    assert compare_offer(None, n1).robust is False
    p1 = _results("P1")
    assert compare_offer(1, p1).robust is False
    assert compare_offer(1, p1).notice is None
