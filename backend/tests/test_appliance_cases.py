def unverified(rule: ApplianceRule) -> ApplianceRule:
    """쓰는 블록을 verified: false로 바꾼 규칙 (A-32)."""
    off = {"verified": False}
    return rule.model_copy(
        update={
            "items": rule.items.model_copy(update=off),
            "lifespan_rule": rule.lifespan_rule.model_copy(update=off),
            "depreciation": rule.depreciation.model_copy(update=off),
            "resolution_table": rule.resolution_table.model_copy(update=off),
        }
    )


def inp(data: dict[str, Any]) -> ApplianceInput:
    return ApplianceInput.model_validate_json(json.dumps(data))


def rule_for(case: dict[str, Any]) -> ApplianceRule:
    rule = load_appliance_rule()
    return rule if case["verified"] else unverified(rule)


def test_case_list() -> None:
    assert list(CASES) == [f"A-{n}" for n in range(1, 35)]


@pytest.mark.parametrize("cid", list(CASES))
def test_appliance_case(cid: str) -> None:
    case = CASES[cid]
    e = case["expected"]
    rule = rule_for(case)
    i = inp(case["input"])
    r = calculate_appliance(i, rule)
    assert r.badge == Badge(e["badge"])
    assert [f.value for f in r.flags] == e["flags"]
    assert r.missing == e["missing"]
    assert r.amount == e["amount"]
    assert [n.value for n in r.notices] == e["notices"]
    assert r.citations == e["citations"]
    if "min" in e:
        assert (r.sensitivity_min, r.sensitivity_max) == (e["min"], e["max"])
        assert r.sensitivity_causes == e["causes"]
    d = build_appliance_display(r, rule, i)
    assert (d.screen_line.text if d.screen_line else None) == e["screen"]
    assert [x.text for x in d.other_flags] == e["folded"]
    g = build_appliance_guide(i, r, rule)
    assert (g.company_message is not None) == e["company"]
